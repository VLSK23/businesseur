// Textes qui contiennent une partie variable (nom d'un projet, nombre, message d'erreur…)
const MOTIFS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^(.+) \| La Gazette du Businesseur$/, (m) => `${traduire(m[1]) ?? m[1]} | The Businesseur Gazette`],
  [/^Suivre (.+) \| Businesseur$/, (m) => `Follow ${m[1]} | Businesseur`],
  [/^(.+) \| Businesseur$/, (m) => `${traduire(m[1]) ?? m[1]} | Businesseur`],
  [/^Vous suivez déjà (.+)\.$/, (m) => `You already follow ${m[1]}.`],
  [/^Merci ! Vous recevrez les nouvelles de (.+)\.$/, (m) => `Thank you! You'll receive news from ${m[1]}.`],
  [
    /^(.+?) : (.+) Le projet est au stade « (.+) »\.$/,
    (m) => `${m[1]}: ${traduire(m[2]) ?? m[2]} The project is at the “${traduire(m[3]) ?? m[3]}” stage.`,
  ],
  [/^Voir (.+)$/, (m) => `See ${m[1]}`],
  [/^(\d+) spécialités choisies$/, (m) => `${m[1]} specialities chosen`],
  [/^Erreur : (.*)$/, (m) => `Error: ${m[1]}`],
];

// Renvoie la traduction anglaise d'un texte français, ou null si on ne la connaît pas.
export function traduire(texte: string): string | null {
  const cle = texte.replace(/\s+/g, " ").trim();
  if (!cle) return null;
  if (Object.prototype.hasOwnProperty.call(TRADUCTIONS, cle)) return TRADUCTIONS[cle];
  for (const [motif, remplacer] of MOTIFS) {
    const m = cle.match(motif);
    if (m) {
      const en = remplacer(m);
      return en === cle ? null : en;
    }
  }
  // Liste de choix séparés par des virgules (ex. « Juridique, Tech & produit »)
  if (cle.includes(", ")) {
    const parties = cle.split(", ").map((p) => TRADUCTIONS[p]);
    if (parties.every(Boolean)) return parties.join(", ");
  }
  return null;
}
